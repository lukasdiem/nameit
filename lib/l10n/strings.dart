  String tr(String key, [Map<String, Object>? args]) {
    final lang = Localizations.maybeLocaleOf(this)?.languageCode == 'de' ? 'de' : 'en';
    var s = _strings[lang]![key] ?? _strings['en']![key] ?? key;
    args?.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
    return s;
  }
