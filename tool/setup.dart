// Run once after `flutter create`:   dart run tool/setup.dart
// Adds what the generated Android/iOS files need for this app.
// Safe to run again; works on Windows, macOS and Linux.
import 'dart:io';

/// Some plugins still compile against an older Android SDK than their own
/// dependencies require. This raises every plugin to at least this level.
const minCompileSdk = 36;

void main() {
  _patch(
    'android/app/src/main/AndroidManifest.xml',
    marker: 'android.permission.INTERNET',
    find: RegExp(r'(<manifest[^>]*>)'),
    insert: (m) => '${m[1]}\n    <uses-permission android:name="android.permission.INTERNET"/>',
  );
  _patch(
    'ios/Runner/Info.plist',
    marker: 'NSCameraUsageDescription',
    find: RegExp(r'(</dict>\s*</plist>)'),
    insert: (m) => '''\t<key>NSCameraUsageDescription</key>
\t<string>The app uses the camera to take student photos.</string>
\t<key>NSPhotoLibraryUsageDescription</key>
\t<string>The app uses your photos to add student pictures.</string>
${m[1]}''',
  );
  _setAppName('nameIT');
  _raiseCompileSdk();
  stdout.writeln('Done. Now run: flutter run');
}

void _raiseCompileSdk() {
  // Groovy is used for this helper because it can set the value on any
  // Android Gradle Plugin version without depending on its Kotlin types.
  File('android/compile_sdk.gradle').writeAsStringSync('''
// Generated by tool/setup.dart. Raises old plugins to compileSdk $minCompileSdk.
subprojects { sp ->
    sp.afterEvaluate { p ->
        def android = p.extensions.findByName('android')
        if (android != null && android.hasProperty('compileSdk')) {
            def current = android.compileSdk
            if (current == null || current < $minCompileSdk) {
                android.compileSdk = $minCompileSdk
            }
        }
    }
}
''');

  // The hook must be applied before the first `subprojects` block, which
  // makes every plugin wait for :app – afterwards it would be too late.
  for (final (path, line) in [
    ('android/build.gradle.kts', 'apply(from = "compile_sdk.gradle")'),
    ('android/build.gradle', "apply from: 'compile_sdk.gradle'"),
  ]) {
    final f = File(path);
    if (!f.existsSync()) continue;
    final s = f.readAsStringSync();
    if (s.contains('compile_sdk.gradle')) {
      stdout.writeln('ok    $path (already set up)');
      return;
    }
    final i = s.indexOf(RegExp(r'^subprojects\b', multiLine: true));
    final patched = i < 0 ? '$s\n$line\n' : '${s.substring(0, i)}$line\n\n${s.substring(i)}';
    f.writeAsStringSync(patched);
    stdout.writeln('patched $path');
    return;
  }
  stdout.writeln('skip  android/build.gradle(.kts) (not found – did you run flutter create?)');
}

/// The name shown under the icon on the home screen.
void _setAppName(String name) {
  for (final (path, find, replace) in [
    ('android/app/src/main/AndroidManifest.xml', RegExp(r'android:label="[^"]*"'), 'android:label="$name"'),
    ('ios/Runner/Info.plist', RegExp(r'(<key>CFBundleDisplayName</key>\s*<string>)[^<]*(</string>)'), null),
  ]) {
    final f = File(path);
    if (!f.existsSync()) {
      stdout.writeln('skip  $path (not found – did you run flutter create?)');
      continue;
    }
    final s = f.readAsStringSync();
    final patched = replace != null
        ? s.replaceFirst(find, replace)
        : s.replaceFirstMapped(find, (m) => '${m[1]}$name${m[2]}');
    if (patched == s) {
      stdout.writeln('ok    $path (name already set)');
    } else {
      f.writeAsStringSync(patched);
      stdout.writeln('patched $path (app name)');
    }
  }
}

void _patch(String path, {required String marker, required RegExp find, required String Function(Match) insert}) {
  final f = File(path);
  if (!f.existsSync()) {
    stdout.writeln('skip  $path (not found – did you run flutter create?)');
    return;
  }
  final s = f.readAsStringSync();
  if (s.contains(marker)) {
    stdout.writeln('ok    $path (already set up)');
    return;
  }
  f.writeAsStringSync(s.replaceFirstMapped(find, insert));
  stdout.writeln('patched $path');
}
